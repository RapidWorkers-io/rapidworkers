"""Go output for scripts/codegen.py.

Writes go/tools_gen.go (one typed method per tool on *Client, a Params struct
per tool and a named string type per enum) and go/cmd/rapidworkers-mcp/tools.json
(the spec snapshot the stdio relay embeds). The Go source is written already
gofmt-formatted, so generating and --check need no Go toolchain; the Go tests
and `gofmt -l` in CI confirm it.
"""
from __future__ import annotations

import json
import re
import textwrap
from pathlib import Path

GO_HEADER = "// Code generated by scripts/codegen.py from spec/tools.json. DO NOT EDIT."
IDEMPOTENCY_KEY = "idempotency_key"
WIDTH = 80

INITIALISMS = {
    "ai": "AI", "api": "API", "http": "HTTP", "id": "ID", "ip": "IP", "iso": "ISO", "json": "JSON",
    "mcp": "MCP", "sms": "SMS", "uri": "URI", "url": "URL", "uuid": "UUID",
}

# Type names for enums and objects whose argument name alone is too generic or
# means different things in different tools. Keys are (tool, argument path).
# Anything not listed is named automatically.
TYPE_NAMES = {
    ("get_platform_info", "section"): "PlatformInfoSection",
    ("get_deposit_link", "method"): "DepositMethod",
    ("create_prefilled_job", "type"): "PrefilledJobType",
    ("create_ai_task", "task_type"): "AITaskType",
    ("create_ai_task", "submission_fields"): "SubmissionField",
    ("create_ai_task", "submission_fields.type"): "SubmissionFieldType",
    ("list_jobs", "status"): "JobStatus",
    ("list_submissions", "status"): "SubmissionStatus",
}

# Exported identifiers written by hand in go/*.go.
RESERVED = {
    "APIError", "APIKeyEnv", "APIKeysURL", "AuthenticationError", "BaseURLEnv", "Bool", "CallTool", "Client",
    "ConnectionError", "DefaultMaxRetries", "DefaultTimeout", "ErrNoAPIKey", "Float", "Int", "ListTools",
    "NewClient", "NewClientFromEnv", "Option", "ProtocolVersion", "Ptr", "RateLimitError", "ServerURL",
    "ServiceUnavailableError", "String", "ToolError", "Version", "WithBaseURL", "WithHTTPClient",
    "WithMaxRetries", "WithTimeout",
}


def go_name(name: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    return "".join(INITIALISMS.get(p.lower(), p[:1].upper() + p[1:]) for p in parts)


def go_string(value: str) -> str:
    # JSON string escapes are valid Go escapes (json.dumps never writes \/).
    return json.dumps(value, ensure_ascii=False)


def singular(name: str) -> str:
    return name[:-1] if name.endswith("s") and not name.endswith("ss") else name


def is_string_enum(schema: dict) -> bool:
    return schema.get("type") == "string" and "enum" in schema


class Generator:
    def __init__(self, spec: dict, helpers: dict) -> None:
        self.spec = spec
        self.tools = spec["tools"]
        self.tool_meta = helpers["tool_meta"]
        self.params = helpers["params"]
        self.names: dict[tuple[str, str], str] = {}  # (tool, path) -> Go type name
        self.enums: dict[str, dict] = {}  # name -> {values, prop, description}
        self.structs: dict[str, dict] = {}  # name -> {tool, path, schema}
        self.taken: set[str] = set(RESERVED)
        self._name_types()

    # ------------------------------------------------------------------ naming

    def _claim(self, name: str, what: str) -> None:
        if not name or not name[0].isalpha() or name in self.taken:
            raise SystemExit(f"gen_go: Go name {name!r} for {what} is invalid or already used; add it to TYPE_NAMES")
        self.taken.add(name)

    def _name_types(self) -> None:
        enums: list[tuple[str, str, str, tuple, str]] = []
        objects: list[tuple[str, str, str, dict, bool]] = []

        def visit(tool: str, path: str, prop: str, schema: dict, description: str, item: bool) -> None:
            if is_string_enum(schema):
                enums.append((tool, path, prop, tuple(schema["enum"]), description))
            elif schema.get("type") == "array":
                items = schema.get("items") or {}
                visit(tool, path, prop, items, items.get("description") or description, True)
            elif schema.get("type") == "object" and schema.get("properties"):
                objects.append((tool, path, prop, schema, item))
                for sub, sub_schema in schema["properties"].items():
                    visit(tool, f"{path}.{sub}", sub, sub_schema, sub_schema.get("description", ""), False)

        for tool in self.tools:
            for prop, schema, _ in self.params(tool):
                visit(tool["name"], prop, prop, schema, schema.get("description", ""), False)

        for method in (go_name(t["name"]) for t in self.tools):
            self._claim(method, "a tool method")
            self._claim(method + "Params", "a params struct")

        for tool, path, prop, schema, item in objects:
            name = TYPE_NAMES.get((tool, path)) or go_name(singular(prop) if item else prop)
            known = self.structs.get(name)
            if known and known["schema"] != schema:
                name = go_name(tool) + name
                known = self.structs.get(name)
            if not known:
                self._claim(name, f"{tool}.{path}")
                self.structs[name] = {"tool": tool, "path": path, "schema": schema}
            self.names[(tool, path)] = name

        value_sets: dict[str, set[tuple]] = {}
        for _, _, prop, values, _ in enums:
            value_sets.setdefault(prop, set()).add(values)
        by_values: dict[tuple[str, tuple], str] = {}
        for tool, path, prop, values, description in enums:
            name = TYPE_NAMES.get((tool, path)) or by_values.get((prop, values))
            if not name:
                name = go_name(prop) if len(value_sets[prop]) == 1 else go_name(tool) + go_name(prop)
            known = self.enums.get(name)
            if known is None:
                self._claim(name, f"{tool}.{path}")
                for value in values:
                    self._claim(self.const_name(name, value), f"a value of {name}")
                parent = path.rpartition(".")[0]
                owner = self.names.get((tool, parent)) if parent else None
                self.enums[name] = {"values": values, "prop": prop, "description": description, "owner": owner}
            elif known["values"] != values:
                raise SystemExit(f"gen_go: enum {name} has two different value sets; add {tool}.{path} to TYPE_NAMES")
            by_values.setdefault((prop, values), name)
            self.names[(tool, path)] = name

    @staticmethod
    def const_name(type_name: str, value: object) -> str:
        suffix = go_name(str(value))
        if not suffix:
            raise SystemExit(f"gen_go: cannot name the value {value!r} of {type_name}")
        return type_name + suffix

    def go_type(self, tool: str, path: str, schema: dict) -> str:
        kind = schema.get("type")
        if is_string_enum(schema) or (kind == "object" and schema.get("properties")):
            return self.names[(tool, path)]
        if kind == "string":
            return "string"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float64"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return "[]" + self.go_type(tool, path, schema.get("items") or {})
        if kind == "object":
            return "map[string]any"
        return "any"

    # ------------------------------------------------------------------ rendering

    @staticmethod
    def comment(text: str, indent: str = "") -> list[str]:
        """A Go comment; each line of text becomes its own paragraph.

        Unlike the shared wrap helper this never breaks a word at a hyphen or
        splits a long word (URLs), so a comment line cannot start with "-".
        """
        prefix = indent + "// "
        out: list[str] = []
        for paragraph in (p.strip() for p in text.split("\n")):
            if not paragraph:
                continue
            if out:
                out.append(prefix.rstrip())
            out += textwrap.wrap(
                paragraph, width=WIDTH, initial_indent=prefix, subsequent_indent=prefix,
                break_on_hyphens=False, break_long_words=False,
            )
        return out

    def field(self, tool: str, path: str, name: str, schema: dict, required: bool, indent: str = "\t") -> list[str]:
        gotype = self.go_type(tool, path, schema)
        nilable = gotype.startswith(("[]", "map[")) or gotype == "any"
        description = schema.get("description", "").strip()
        if name == IDEMPOTENCY_KEY:
            gotype, omit = "string", True
            description = re.sub(r"^Optional\.\s*", "", description)
            description = "Optional. Created automatically when empty and reused on retries. " + description
        elif required:
            omit = False
            description = ("Required. " + description).strip()
        elif is_string_enum(schema) or nilable:
            omit = True  # the zero value ("" or nil) is never a valid argument
        else:
            gotype, omit = "*" + gotype, True
        tag = f'`json:"{name}{",omitempty" if omit else ""}"`'
        lines = self.comment(description, indent) if description else []
        return lines + [f"{indent}{go_name(name)} {gotype} {tag}"]

    def struct_body(self, tool: str, fields: list[tuple[str, str, dict, bool]]) -> list[str]:
        out: list[str] = []
        seen: set[str] = set()
        for i, (path, name, schema, required) in enumerate(fields):
            if not go_name(name) or go_name(name) in seen:
                raise SystemExit(f"gen_go: {tool}.{path} has no Go field name of its own")
            seen.add(go_name(name))
            if i:
                out.append("")
            out += self.field(tool, path, name, schema, required)
        return out

    def render_enum(self, name: str, info: dict) -> list[str]:
        if info["owner"]:
            doc = f'{name} is a value of the "{info["prop"]}" field of [{info["owner"]}].'
        else:
            doc = f'{name} is a value of the "{info["prop"]}" argument.'
        if info["description"]:
            doc += "\n" + info["description"]
        out = self.comment(doc)
        out.append(f"type {name} string")
        out.append("")
        out.append(f"// Values of {name}.")
        out.append("const (")
        consts = [(self.const_name(name, v), v) for v in info["values"]]
        width = max(len(c) for c, _ in consts)
        out += [f"\t{c.ljust(width)} {name} = {go_string(str(v))}" for c, v in consts]
        out.append(")")
        return out

    def render_struct(self, name: str, info: dict) -> list[str]:
        schema = info["schema"]
        required = set(schema.get("required") or [])
        doc = f'{name} is one element of the "{info["path"].split(".")[-1]}" argument.'
        if schema.get("description"):
            doc += "\n" + schema["description"]
        out = self.comment(doc)
        out.append(f"type {name} struct {{")
        props = schema["properties"]
        ordered = [p for p in props if p in required] + [p for p in props if p not in required]
        fields = [(f"{info['path']}.{p}", p, props[p], p in required) for p in ordered]
        out += self.struct_body(info["tool"], fields)
        out.append("}")
        return out

    def method_sentence(self, method: str, description: str) -> str:
        first, _, rest = description.partition(" ")
        if re.fullmatch(r"[A-Z][a-z]+", first):
            return f"{method} {first.lower()} {rest}".rstrip()
        return f"{method} calls the tool. {description}".rstrip()

    def render_tool(self, tool: dict) -> list[str]:
        name = tool["name"]
        method = go_name(name)
        meta = self.tool_meta(tool)
        args = self.params(tool)
        out: list[str] = []
        if args:
            out += [f"// {method}Params are the arguments of [Client.{method}].", f"type {method}Params struct {{"]
            out += self.struct_body(name, [(arg, arg, schema, required) for arg, schema, required in args])
            out += ["}", ""]
        doc = self.method_sentence(method, tool.get("description", "").strip())
        note = f'It calls the "{name}" tool.'
        if meta["idempotency_key"]:
            note += (
                " An empty p.IdempotencyKey is replaced by a new key, which is reused when"
                " the call is retried, so the action never happens twice."
            )
        elif not meta["retry"]:
            note += " It is not resent after a network or gateway error, because it may already have run."
        out += self.comment(doc + "\n" + note)
        if args:
            out.append(f"func (c *Client) {method}(ctx context.Context, p {method}Params) (map[string]any, error) {{")
            if meta["idempotency_key"]:
                out += [
                    "\tif err := ensureIdempotencyKey(&p.IdempotencyKey); err != nil {",
                    "\t\treturn nil, err",
                    "\t}",
                ]
            out.append(f"\treturn c.callTool(ctx, {go_string(name)}, p)")
        else:
            out.append(f"func (c *Client) {method}(ctx context.Context) (map[string]any, error) {{")
            out.append(f"\treturn c.callTool(ctx, {go_string(name)}, struct{{}}{{}})")
        out.append("}")
        return out

    def render(self) -> str:
        out = [
            GO_HEADER,
            "",
            "package rapidworkers",
            "",
            'import "context"',
            "",
            "// ServerURL is the hosted RapidWorkers MCP endpoint and the default base URL.",
            f"const ServerURL = {go_string(self.spec['server']['url'])}",
            "",
            "// toolTable says how each tool may be retried and whether it takes an",
            "// idempotency key.",
            "var toolTable = []toolInfo{",
        ]
        for tool in self.tools:
            meta = self.tool_meta(tool)
            out.append(
                f"\t{{name: {go_string(tool['name'])}, readOnly: {str(meta['read_only']).lower()}, "
                f"idempotencyKey: {str(meta['idempotency_key']).lower()}, retry: {str(meta['retry']).lower()}}},"
            )
        out.append("}")
        for name in sorted(self.enums):
            out.append("")
            out += self.render_enum(name, self.enums[name])
        for name in sorted(self.structs):
            out.append("")
            out += self.render_struct(name, self.structs[name])
        for tool in self.tools:
            out.append("")
            out += self.render_tool(tool)
        return "\n".join(out) + "\n"


def outputs(spec: dict, root: Path, helpers: dict) -> dict:
    generator = Generator(spec, helpers)
    return {
        root / "go" / "tools_gen.go": generator.render,
        root / "go" / "cmd" / "rapidworkers-mcp" / "tools.json": helpers["spec_json"],
    }
