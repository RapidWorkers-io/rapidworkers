#!/usr/bin/env python3
"""Generate the typed tool methods of every SDK from spec/tools.json.

spec/tools.json is the exact tools/list answer of the hosted RapidWorkers MCP
server (exported from the server's own tool catalog). Each SDK gets one method
per tool; the hand-written client in each package does the HTTP work.

    python3 scripts/codegen.py          # write the generated files
    python3 scripts/codegen.py --check  # exit 1 if any generated file is stale
"""
from __future__ import annotations

import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec" / "tools.json").read_text())
HEADER = "Generated by scripts/codegen.py from spec/tools.json. Do not edit by hand."

IDEMPOTENCY_KEY = "idempotency_key"


def tool_meta(tool: dict) -> dict:
    """How the clients may treat a tool: retry on network errors, auto key."""
    annotations = tool.get("annotations") or {}
    props = tool["inputSchema"].get("properties", {})
    has_key = IDEMPOTENCY_KEY in props
    return {
        "read_only": bool(annotations.get("readOnlyHint")),
        "idempotency_key": has_key,
        # Safe to resend after a timeout: nothing changes, or the server
        # dedupes the call by its idempotency key.
        "retry": bool(annotations.get("readOnlyHint") or annotations.get("idempotentHint") or has_key),
    }


def params(tool: dict) -> list[tuple[str, dict, bool]]:
    """(name, schema, required) with required parameters first.

    idempotency_key is always optional in the SDKs: the client creates one.
    """
    schema = tool["inputSchema"]
    required = set(schema.get("required") or []) - {IDEMPOTENCY_KEY}
    props = schema.get("properties", {})
    ordered = [n for n in props if n in required] + [n for n in props if n not in required]
    return [(n, props[n], n in required) for n in ordered]


def wrap(text: str, width: int, indent: str) -> list[str]:
    lines: list[str] = []
    for paragraph in text.split("\n"):
        lines.extend(textwrap.wrap(paragraph, width=width, initial_indent=indent, subsequent_indent=indent) or [indent.rstrip()])
    return lines


# --------------------------------------------------------------------------- Python


def py_type(schema: dict) -> str:
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    kind = schema.get("type")
    if kind == "string":
        return "str"
    if kind == "number":
        return "float"
    if kind == "integer":
        return "int"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"Sequence[{py_type(schema.get('items') or {})}]"
    return "Mapping[str, Any]"


def py_doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def py_method(tool: dict, is_async: bool) -> list[str]:
    name = tool["name"]
    args = params(tool)
    sig = ["self"]
    if args:
        sig.append("*")
    for arg, schema, required in args:
        hint = py_type(schema)
        sig.append(f"{arg}: {hint}" if required else f"{arg}: {hint} | None = None")
    prefix = "async def" if is_async else "def"
    out = [f"    {prefix} {name}("]
    out += [f"        {part}," for part in sig]
    out.append("    ) -> dict[str, Any]:")
    doc = wrap(py_doc(tool.get("description", "")), 88, "        ")
    doc[0] = '        """' + doc[0].lstrip()
    out += doc
    if args:
        out += ["", "        Args:"]
        for arg, schema, _ in args:
            desc = schema.get("description", "")
            if arg == IDEMPOTENCY_KEY:
                desc = "Optional. Created automatically when omitted and reused on retries. " + desc
            lines = wrap(py_doc(f"{arg}: {desc}".rstrip()), 84, "            ")
            out += [lines[0]] + ["    " + line for line in lines[1:]]
    out.append('        """')
    call = "await self._call_tool" if is_async else "self._call_tool"
    if args:
        out.append(f"        return {call}(")
        out.append(f'            "{name}",')
        out.append("            {")
        out += [f'                "{arg}": {arg},' for arg, _, _ in args]
        out.append("            },")
        out.append("        )")
    else:
        out.append(f'        return {call}("{name}", {{}})')
    return out


def gen_python() -> str:
    tools = SPEC["tools"]
    lines = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, Mapping, Sequence",
        "",
        f"SERVER_URL = {SPEC['server']['url']!r}",
        "",
        "# How each tool may be retried and whether it takes an idempotency key.",
        "TOOL_META: dict[str, dict[str, bool]] = {",
    ]
    for tool in tools:
        lines.append(f"    {tool['name']!r}: {tool_meta(tool)!r},")
    lines += ["}", ""]
    for cls, is_async in (("SyncTools", False), ("AsyncTools", True)):
        call_sig = (
            "    async def _call_tool(self, name: str, arguments: dict[str, Any]) -> dict[str, Any]:"
            if is_async
            else "    def _call_tool(self, name: str, arguments: dict[str, Any]) -> dict[str, Any]:"
        )
        lines += [
            "",
            f"class {cls}:",
            f'    """One method per RapidWorkers MCP tool ({"async" if is_async else "sync"})."""',
            "",
            call_sig,
            "        raise NotImplementedError",
        ]
        for tool in tools:
            lines.append("")
            lines += py_method(tool, is_async)
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- outputs

def spec_json() -> str:
    return json.dumps(SPEC, indent=2) + "\n"


OUTPUTS = {
    ROOT / "python" / "rapidworkers" / "src" / "rapidworkers" / "_generated.py": gen_python,
    ROOT / "python" / "rapidworkers-mcp" / "src" / "rapidworkers_mcp" / "tools.json": spec_json,
}


def plugin_outputs() -> dict:
    """Other languages live in scripts/gen_<language>.py.

    Each module defines outputs(spec, root, helpers) -> {Path: callable returning str}.
    helpers gives the shared tool_meta, params, wrap and spec_json functions.
    """
    import importlib.util

    helpers = {"tool_meta": tool_meta, "params": params, "wrap": wrap, "spec_json": spec_json, "HEADER": HEADER}
    found = {}
    for path in sorted(Path(__file__).parent.glob("gen_*.py")):
        module_spec = importlib.util.spec_from_file_location(path.stem, path)
        module = importlib.util.module_from_spec(module_spec)
        module_spec.loader.exec_module(module)
        found.update(module.outputs(SPEC, ROOT, helpers))
    return found


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, build in {**OUTPUTS, **plugin_outputs()}.items():
        content = build()
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated files (run python3 scripts/codegen.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
